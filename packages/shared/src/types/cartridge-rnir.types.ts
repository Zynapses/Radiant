/**
 * Domain signature for RNIR compilation
 * Aligned with Axiom domain signatures
 */
export interface RNIRDomainSignature {
  /** Domain ID (e.g., "legal.contracts.saas") */
  domainId: string;
  
  /** Role template for this domain */
  roleTemplate: string;
  
  /** Template parameters */
  roleParameters: Record<string, string>;
  
  /** Required context fields */
  requiredContext: string[];
  
  /** Domain-specific constraints */
  domainConstraints: string[];
  
  /** Output format specification */
  outputFormat: string;
  
  /** Model preferences for this domain */
  modelPreferences: {
    primaryModel: string;
    requiredProficiencies: Record<string, number>;
    fallbackChain: string[];
    thinkingMethod: 'standard' | 'extended' | 'budget';
  };
  
  /** Model-specific prompt variants */
  modelVariants: {
    claude?: string;
    gpt?: string;
    gemini?: string;
    llama?: string;
    qwen?: string;
    mistral?: string;
  };
}

