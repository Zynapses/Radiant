/**
 * RNIR (Radiant Neural Intermediate Representation) Types
 * 
 * Model-agnostic "cognitive source code" that can be compiled into:
 * - LoRA weights for self-hosted models (Cortex)
 * - System prompts for external APIs (OpenAI, Claude, etc.)
 * 
 * @version 1.0.0
 * @since v6.2.0
 */

// =============================================================================
// RNIR Core Types
// =============================================================================

/**
 * Single RNIR training example
 */
export interface RNIRExample {
  /** User input/prompt */
  user: string;
  
  /** Expected assistant response */
  assistant: string;
  
  /** Optional system context for this example */
  system?: string;
  
  /** Domain this example belongs to */
  domain?: string;
  
  /** Tags for categorization */
  tags?: string[];
  
  /** Quality score (0-1) */
  quality?: number;
  
  /** Source of this example (curator, manual, synthetic) */
  source?: 'curator' | 'manual' | 'synthetic' | 'imported';
  
  /** Metadata */
  metadata?: Record<string, unknown>;
}

/**
 * RNIR document (rnir.jsonl parsed)
 */
export interface RNIRDocument {
  /** Schema version */
  version: '1.0';
  
  /** Cartridge ID */
  cartridgeId: string;
  
  /** Domain this RNIR is for */
  domain: string;
  
  /** Training examples */
  examples: RNIRExample[];
  
  /** Total example count */
  exampleCount: number;
  
  /** Created timestamp */
  createdAt: string;
  
  /** Last modified timestamp */
  modifiedAt: string;
  
  /** Generated by (curator version, etc.) */
  generatedBy: string;
}

// =============================================================================
// Compilation Targets
// =============================================================================

/**
 * Target format for RNIR compilation
 */
export type RNIRCompilationTarget = 
  | 'lora'              // LoRA weights for fine-tuning
  | 'system_prompt'     // System prompt injection
  | 'few_shot'          // Few-shot examples
  | 'rag_chunks'        // RAG knowledge chunks
  | 'all';              // All formats

/**
 * Model family for compilation
 */
export type RNIRModelFamily = 
  | 'llama'             // Meta Llama models
  | 'qwen'              // Alibaba Qwen models
  | 'mistral'           // Mistral AI models
  | 'claude'            // Anthropic Claude (external)
  | 'gpt'               // OpenAI GPT (external)
  | 'gemini'            // Google Gemini (external)
  | 'universal';        // Generic format

/**
 * LoRA compilation settings
 */
export interface LoRACompilationSettings {
  /** Target model family */
  modelFamily: RNIRModelFamily;
  
  /** Specific model ID (e.g., "llama-3.1-8b") */
  modelId: string;
  
  /** LoRA rank (default: 16) */
  rank: number;
  
  /** LoRA alpha (default: 32) */
  alpha: number;
  
  /** Dropout (default: 0.05) */
  dropout: number;
  
  /** Target modules */
  targetModules: string[];
  
  /** Learning rate */
  learningRate: number;
  
  /** Epochs */
  epochs: number;
  
  /** Batch size */
  batchSize: number;
}

/**
 * System prompt compilation settings
 */
export interface SystemPromptCompilationSettings {
  /** Target model family */
  modelFamily: RNIRModelFamily;
  
  /** Maximum prompt length */
  maxLength: number;
  
  /** Include few-shot examples */
  includeFewShot: boolean;
  
  /** Number of few-shot examples */
  fewShotCount: number;
  
  /** Prompt template style */
  templateStyle: 'minimal' | 'detailed' | 'structured';
}

/**
 * Compilation request
 */
export interface RNIRCompilationRequest {
  /** Cartridge ID */
  cartridgeId: string;
  
  /** Target format */
  target: RNIRCompilationTarget;
  
  /** Model family */
  modelFamily: RNIRModelFamily;
  
  /** LoRA settings (if target is 'lora') */
  loraSettings?: LoRACompilationSettings;
  
  /** System prompt settings (if target is 'system_prompt') */
  systemPromptSettings?: SystemPromptCompilationSettings;
  
  /** Priority (1-10) */
  priority?: number;
}

// =============================================================================
// Compilation Results
// =============================================================================

/**
 * Compilation status
 */
export type RNIRCompilationStatus = 
  | 'pending'
  | 'queued'
  | 'compiling'
  | 'completed'
  | 'failed'
  | 'cancelled';

/**
 * Compiled artifact
 */
export interface RNIRCompiledArtifact {
  /** Artifact ID */
  id: string;
  
  /** Cartridge ID */
  cartridgeId: string;
  
  /** Compilation target */
  target: RNIRCompilationTarget;
  
  /** Model family */
  modelFamily: RNIRModelFamily;
  
  /** Specific model ID */
  modelId?: string;
  
  /** S3 path to artifact */
  artifactPath: string;
  
  /** Artifact size in bytes */
  sizeBytes: number;
  
  /** SHA-256 checksum */
  checksum: string;
  
  /** Status */
  status: RNIRCompilationStatus;
  
  /** Compilation started at */
  startedAt?: string;
  
  /** Compilation completed at */
  completedAt?: string;
  
  /** Error message if failed */
  errorMessage?: string;
  
  /** Compilation metrics */
  metrics?: {
    trainingLoss?: number;
    validationLoss?: number;
    examplesProcessed: number;
    compilationTimeSeconds: number;
  };
  
  /** Created timestamp */
  createdAt: string;
}

/**
 * Compilation job
 */
export interface RNIRCompilationJob {
  /** Job ID */
  id: string;
  
  /** Tenant ID */
  tenantId: string;
  
  /** Request */
  request: RNIRCompilationRequest;
  
  /** Status */
  status: RNIRCompilationStatus;
  
  /** Progress (0-100) */
  progress: number;
  
  /** Current step description */
  currentStep?: string;
  
  /** Artifacts produced */
  artifacts: RNIRCompiledArtifact[];
  
  /** Started at */
  startedAt?: string;
  
  /** Completed at */
  completedAt?: string;
  
  /** Error if failed */
  error?: string;
  
  /** Created at */
  createdAt: string;
}

