// =============================================================================
// Cortex Integration (from v4.21.0 spec)
// =============================================================================

/**
 * Knowledge density from Cortex for RNIR compilation decisions
 * Aligned with cortex-intelligence.service.ts
 */
export interface RNIRKnowledgeDensity {
  /** Total graph nodes for this domain */
  totalNodes: number;
  
  /** Total graph edges */
  totalEdges: number;
  
  /** Knowledge depth classification */
  knowledgeDepth: 'none' | 'sparse' | 'moderate' | 'rich' | 'expert';
  
  /** Confidence boost from existing knowledge (0.0-0.3) */
  confidenceBoost: number;
  
  /** Top domains with most knowledge */
  topDomains: string[];
  
  /** Key entities from graph */
  keyEntities: string[];
}

/**
 * Cortex-aware compilation that considers existing knowledge
 */
export interface RNIRCortexAwareCompilation {
  /** Should use existing Cortex knowledge? */
  useCortexKnowledge: boolean;
  
  /** Knowledge density assessment */
  knowledgeDensity: RNIRKnowledgeDensity;
  
  /** Nodes to incorporate from Cortex warm tier */
  incorporateNodeIds?: string[];
  
  /** Max nodes to use (per orchestration recommendation) */
  maxNodes: number;
  
  /** Domain boost from Cortex */
  domainBoosts: Record<string, number>;
}

// =============================================================================
// Twilight Dreaming Integration (from v4.21.0 spec)
// =============================================================================

/**
 * Twilight Dreaming task for RNIR compilation
 * Runs during off-hours (nightly 2am UTC)
 */
export type TwilightTaskType = 
  | 'compile_lora'       // Heavy LoRA training
  | 'generate_rnir'      // Extract RNIR from Curator
  | 'optimize_prompts'   // Optimize system prompts
  | 'infer_examples'     // Generate synthetic examples
  | 'merge_domains';     // Merge overlapping domain knowledge

export interface RnirTwilightTask {
  /** Task ID */
  taskId: string;
  
  /** Tenant ID */
  tenantId: string;
  
  /** Task type */
  taskType: TwilightTaskType;
  
  /** Priority (1-10, higher = more important) */
  priority: number;
  
  /** Scope of task */
  scope: 'local' | 'domain' | 'global';
  
  /** Input parameters */
  parameters: Record<string, unknown>;
  
  /** Scheduled time */
  scheduledAt: string;
  
  /** Status */
  status: 'scheduled' | 'running' | 'completed' | 'failed' | 'cancelled';
  
  /** Started at */
  startedAt?: string;
  
  /** Completed at */
  completedAt?: string;
  
  /** Result summary */
  result?: RnirTwilightResult;
  
  /** Error if failed */
  error?: string;
}

export interface RnirTwilightResult {
  /** Artifacts created */
  artifactsCreated: number;
  
  /** Examples processed */
  examplesProcessed: number;
  
  /** Bytes processed */
  bytesProcessed: number;
  
  /** Duration in seconds */
  durationSeconds: number;
  
  /** Estimated cost */
  estimatedCostCents: number;
  
  /** Improvement metrics */
  improvements?: {
    accuracyDelta?: number;
    tokensSaved?: number;
    latencyReduction?: number;
  };
}

/**
 * Schedule RNIR compilation for Twilight Dreaming
 */
export interface ScheduleTwilightRNIRRequest {
  /** Cartridge ID */
  cartridgeId: string;
  
  /** Task type */
  taskType: TwilightTaskType;
  
  /** Priority (1-10) */
  priority?: number;
  
  /** Target model family */
  modelFamily?: RNIRModelFamily;
  
  /** Run immediately (bypass scheduling)? */
  runImmediately?: boolean;
}

