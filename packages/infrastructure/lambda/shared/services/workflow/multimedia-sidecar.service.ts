/**
 * Multimedia Sidecar Service
 * RADIANT v5.53.0
 * 
 * Implements Gemini's "Sidecar & Bridge" pattern for multimedia orchestration:
 * 
 * 1. COGNITIVE SIDECARS: Pre-computed representations for cross-modal evaluation
 *    - Transcriptions for audio/video
 *    - Frame samples for video
 *    - Embeddings for semantic search (CLIP/SigLIP)
 *    - Alt-text descriptions
 * 
 * 2. AUTO-BRIDGING: Automatic cross-modal condition evaluation
 *    - Text condition on video? Use sidecar.transcription
 *    - Semantic condition on image? Use sidecar.embedding
 *    - Workflows "just work" regardless of modality
 * 
 * 3. ZERO-COPY: Never put blobs in envelopes, only S3 URIs + sidecars
 */

import { v4 as uuidv4 } from 'uuid';
import { enhancedLogger as logger } from '../../logging/enhanced-logger';
import { modelRouterService } from '../model-router.service';

// =============================================================================
// Types
// =============================================================================

export type MediaType = 'text' | 'image' | 'audio' | 'video' | 'document' | 'binary';

export type SidecarStatus = 'pending' | 'processing' | 'complete' | 'failed' | 'partial';

/**
 * Cognitive Sidecar - Pre-computed representations for cross-modal AI
 * This is what gets passed between workflow nodes, NOT the raw media
 */
export interface CognitiveSidecar {
  sidecarId: string;
  version: '1.0';
  status: SidecarStatus;
  generatedAt: string;
  
  // Text representation (for text-only models)
  transcription?: {
    text: string;
    language: string;
    confidence: number;
    segments?: Array<{
      start: number;
      end: number;
      text: string;
    }>;
  };
  
  // Visual samples (for vision models)
  frameSamples?: Array<{
    timestampMs: number;
    signedUrl: string;
    urlExpiresAt: string;
    description?: string;
  }>;
  
  // Vector embeddings (for semantic search/routing)
  embedding?: {
    model: string; // e.g., 'clip-vit-large', 'siglip-so400m'
    dimensions: number;
    vector: number[];
    normalizedL2: boolean;
  };
  
  // Alt-text / description (generated by vision model)
  description?: {
    short: string;    // ~50 chars
    medium: string;   // ~200 chars
    detailed: string; // Full description
    modelUsed: string;
  };
  
  // Document-specific (for PDFs, DOCX, etc.)
  documentContent?: {
    extractedText: string;
    pageCount?: number;
    structure?: {
      headings: string[];
      tables: number;
      images: number;
    };
  };
  
  // Metadata extracted from media
  metadata?: {
    duration?: number;     // seconds for audio/video
    width?: number;
    height?: number;
    pageCount?: number;
    wordCount?: number;
    mimeType?: string;
    fileSizeBytes?: number;
  };
  
  // Processing errors (if partial/failed)
  errors?: Array<{
    component: string;
    message: string;
    recoverable: boolean;
  }>;
}

/**
 * Multimedia Stream with Sidecar (Gemini pattern)
 * The envelope contains this, NOT raw media bytes
 */
export interface MultimediaStream {
  streamId: string;
  mediaType: MediaType;
  
  // 1. The Pointer (Zero-Copy)
  sourceUri: string; // "s3://radiant-uploads/tenant_123/session_456/video.mp4"
  
  // 2. Access credentials
  access?: {
    signedUrl?: string;
    signedUrlExpiresAt?: string;
    accessMethod: 'presigned_url' | 'iam_role' | 'public';
  };
  
  // 3. The Cognitive Sidecar (generated on ingest)
  sidecar: CognitiveSidecar;
  
  // 4. Original metadata
  originalFilename?: string;
  uploadedAt?: string;
  uploadedBy?: string;
}

/**
 * Sidecar generation options
 */
export interface SidecarGenerationOptions {
  generateTranscription?: boolean;
  generateFrameSamples?: boolean;
  frameSampleCount?: number;
  generateEmbedding?: boolean;
  embeddingModel?: 'clip-vit-large' | 'siglip-so400m' | 'text-embedding-3-small';
  generateDescription?: boolean;
  descriptionModel?: string;
  extractDocumentContent?: boolean;
  maxProcessingTimeMs?: number;
}

/**
 * Bridge result when auto-bridging cross-modal conditions
 */
export interface BridgeResult {
  bridged: boolean;
  sourceModality: MediaType;
  targetModality: MediaType;
  bridgeMethod: 'transcription' | 'description' | 'embedding' | 'document_text' | 'direct';
  content: unknown;
  confidence: number;
  warning?: string;
}

